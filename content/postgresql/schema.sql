CREATE TABLE roles (
    id integer PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE
);
CREATE TABLE users (
    id integer PRIMARY KEY,
    login varchar(100) COLLATE "C" NOT NULL UNIQUE,
    last_name varchar(100) NOT NULL,
    first_name varchar(100) NOT NULL,
    patronymic varchar(100) NOT NULL,
    role_id integer NOT NULL REFERENCES roles(id)
);
CREATE TABLE categories (
    id integer PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE
);
CREATE TABLE subcategories (
    id integer PRIMARY KEY,
    category_id integer NOT NULL REFERENCES categories(id),
    name varchar(100) NOT NULL,
    UNIQUE (category_id, name)
);
CREATE TABLE manufacturers (
    id integer PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE
);
CREATE TABLE products (
    id integer PRIMARY KEY,
    subcategory_id integer NOT NULL REFERENCES subcategories(id),
    manufacturer_id integer NOT NULL REFERENCES manufacturers(id),
    name varchar(250) NOT NULL,
    image varchar(250) NOT NULL,
    composition text NOT NULL,
    description text NOT NULL,
    price numeric(12,2) NOT NULL CHECK (price >= 0),
    UNIQUE (name, manufacturer_id)
);
CREATE TABLE sizes (
    id integer PRIMARY KEY,
    label varchar(10) NOT NULL UNIQUE,
    sort_value numeric(5,1) NOT NULL
);
CREATE TABLE stock_items (
    id integer PRIMARY KEY,
    product_id integer NOT NULL REFERENCES products(id),
    size_id integer NOT NULL REFERENCES sizes(id),
    available integer NOT NULL CHECK (available >= 0),
    UNIQUE (product_id, size_id)
);
CREATE TABLE orders (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_date timestamp without time zone NOT NULL,
    user_id integer NOT NULL REFERENCES users(id),
    created_by integer NOT NULL REFERENCES users(id),
    request_id varchar(36) UNIQUE,
    stock_accounted boolean NOT NULL DEFAULT true
);
CREATE TABLE order_items (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    stock_id integer NOT NULL REFERENCES stock_items(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(12,2) NOT NULL CHECK (unit_price >= 0),
    UNIQUE (order_id, stock_id)
);
CREATE INDEX orders_by_date ON orders(order_date);
